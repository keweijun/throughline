let language='en';
const bindings=new WeakMap();
export const getLanguage=()=>language;
export function t(key,values={}){
  const template=language==='zh-CN'?(messages[key]??key):key;
  const params=typeof values==='function'?values():values;
  return template.replace(/\{(\w+)\}/g,(match,name)=>String(params[name]??match));
}
export function bind(node,key,values={},attribute='textContent'){
  let entries=bindings.get(node);
  if(!entries){entries=new Map();bindings.set(node,entries);node.dataset.localized='';}
  entries.set(attribute,{key,values});
  const text=t(key,values);
  if(attribute==='textContent')node.textContent=text;else node.setAttribute(attribute,text);
  return node;
}
export function localize(root=document){
  for(const attribute of ['textContent','placeholder','aria-label','title']){
    const marker=attribute==='textContent'?'data-i18n':'data-i18n-'+attribute;
    const nodes=[...(root.matches?.('['+marker+']')?[root]:[]),...root.querySelectorAll('['+marker+']')];
    for(const node of nodes)bind(node,node.getAttribute(marker),{},attribute);
  }
  for(const node of root.querySelectorAll('[data-localized]')){
    for(const [attribute,{key,values}] of bindings.get(node)||[]){
      const text=t(key,values);
      if(attribute==='textContent')node.textContent=text;else node.setAttribute(attribute,text);
    }
  }
}
export function setLanguage(value){
  language=value==='zh-CN'?'zh-CN':'en';
  document.documentElement.lang=language;
  localize();
}
