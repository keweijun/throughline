const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const {once}=require('node:events');
const assert=require('node:assert/strict');
const child=spawn(process.env.TEST_PYTHON||'python',['-m','tests.branch_recovery_browser_fixture'],{stdio:['ignore','pipe','inherit']});
let browser;
(async()=>{
 const [out]=await once(child.stdout,'data');const base='http://127.0.0.1:'+out.toString().trim();
 browser=await chromium.launch({headless:true});const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto(base,{waitUntil:"networkidle"});
 assert.equal(await page.locator('#turn-a .lesson-title').textContent(),'Older lesson');
 assert.equal(await page.locator('#turn-b .lesson-title').textContent(),'Current lesson');
 const paragraph=page.locator('#turn-a .lesson-body p');await paragraph.scrollIntoViewIfNeeded();const box=await paragraph.boundingBox();
 await page.mouse.move(box.x+2,box.y+10);await page.mouse.down();await page.mouse.move(box.x+240,box.y+10,{steps:10});await page.mouse.up();
 assert.ok((await page.evaluate(()=>window.getSelection().toString())).trim().length>5);
 await page.getByRole('button',{name:'就这句提问',exact:true}).click();
 await page.getByRole('textbox',{name:'旁支问题',exact:true}).fill('Why this older formula?');
 const response=page.waitForResponse(r=>r.url().endsWith('/api/branches/ask')&&r.request().method()==='POST');
 await page.locator('#branch-panel').getByRole('button',{name:'提问',exact:true}).click();
 const reply=await response;const submitted=reply.request().postDataJSON();assert.equal(submitted.selected_turn_id,'a');assert.equal(submitted.main_turn_id,'b');
 const body=await reply.json();assert.equal(body.branch.selected_lecture.id,'a');assert.equal(body.branch.restore_point.concept_id,'b');
 const supplement=page.locator('#branch-panel article').filter({has:page.getByRole('heading',{name:'Need foundations',exact:true})});
 await supplement.locator('.supplement-status').filter({hasText:'中断'}).waitFor();
 assert.match(await supplement.locator('.supplement').textContent(),/Partial supplement/);
 await supplement.getByRole('button',{name:'重新生成补讲',exact:true}).click();
 await supplement.locator('.supplement-status').filter({hasText:'生成中'}).waitFor();
 await supplement.getByRole('button',{name:'暂停补讲',exact:true}).click();
 await supplement.locator('.supplement-status').filter({hasText:'已暂停'}).waitFor();
 await page.reload();
 await page.getByRole('button',{name:'选句提问 / 旁支答疑',exact:true}).click();
 await supplement.getByRole('button',{name:'重新生成补讲',exact:true}).waitFor();
 const state=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));const turn=state.turns.find(t=>t.id==='supplement:recovery');
 assert.equal(turn.status,'paused');assert.equal(turn.attempt,2);assert.equal(state.position.concept_id,'b');
 assert.equal(state.turns.filter(t=>t.id==='supplement:recovery').length,1);
 assert.equal(state.session.recent_interactions.filter(i=>i.id==='stream:supplement:recovery').length,0);
 assert.deepEqual(errors,[]);console.log('PASS: real older-card selection identity; current recovery; interrupted supplement regenerate, pause, reload; no duplicate evidence.');
 await browser.close();child.kill();
})().catch(async e=>{console.error(e);if(browser)await browser.close();child.kill();process.exit(1)});

