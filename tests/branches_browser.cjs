const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const {once}=require('node:events');
const child=spawn(process.env.TEST_PYTHON||'python',['-m','tests.navigation_browser_fixture'],{stdio:['ignore','pipe','inherit']});
let browser;
(async()=>{
 const [out]=await once(child.stdout,'data');
 browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 await page.goto('http://127.0.0.1:'+out.toString().trim());
 await page.locator('#start').click();
 await page.locator('.turn-status').filter({hasText:'讲解已保存'}).waitFor();
 const paragraph=page.locator('.lesson-body p').filter({hasText:'这是完整的讲解段落'}).nth(30);
 await paragraph.scrollIntoViewIfNeeded();
 const box=await paragraph.boundingBox();
 await page.mouse.move(box.x+2,box.y+10);await page.mouse.down();await page.mouse.move(box.x+240,box.y+10,{steps:10});await page.mouse.up();
 const excerpt=await page.evaluate(()=>window.getSelection().toString());
 if(excerpt.trim().length<5)throw Error('Mouse drag did not select a real passage');
 const anchor=await page.evaluate(()=>window.scrollY);
 await page.getByRole('button',{name:'就这句提问',exact:true}).click({timeout:3000});
 if(await page.locator('#branch-selection').textContent()!==excerpt)throw Error('Selected passage lost');
 await page.getByRole('textbox',{name:'旁支问题',exact:true}).fill('这句话是什么意思？');
 await page.locator('#branch-panel').getByRole('button',{name:'提问',exact:true}).click();
 await page.locator('#branch-panel').getByRole('button',{name:'回到主线',exact:true}).waitFor();
 await page.locator('#branch-panel').getByRole('button',{name:'回到主线',exact:true}).click();
 if(Math.abs(await page.evaluate(()=>window.scrollY)-anchor)>2)throw Error('Return moved reading anchor');
 await page.getByRole('button',{name:'选句提问 / 旁支答疑',exact:true}).click();
 if((await page.locator('#branch-selection').textContent()).trim())throw Error('Unrelated question retained stale quote');
 await page.locator('#close-aux').click();
 const formula=page.locator('.lesson-body .katex').first();await formula.scrollIntoViewIfNeeded();
 const fbox=await formula.boundingBox();await page.mouse.move(fbox.x+2,fbox.y+fbox.height/2);await page.mouse.down();await page.mouse.move(fbox.x+fbox.width-2,fbox.y+fbox.height/2,{steps:10});await page.mouse.up();
 await page.getByRole('button',{name:'就这句提问',exact:true}).click();
 if(await page.locator('#branch-selection').textContent()!=='P=|a+b|^2')throw Error('Formula selection lost original TeX');
 await page.getByRole('button',{name:'清除引用，另问一个问题',exact:true}).click();
 if((await page.locator('#branch-selection').textContent()).trim())throw Error('Explicit clear failed');
 console.log(JSON.stringify({result:'PASS',excerpt,anchor,returnAnchor:anchor,checks:'real mouse selection; contextual action; excerpt; durable ask; return scroll; clear stale selection'}));
 await browser.close();child.kill();
})().catch(async e=>{console.error(e);if(browser)await browser.close();child.kill();process.exit(1)});
