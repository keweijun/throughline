export type MessageKey = keyof typeof messages;
export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const template = locale.language === 'zh-CN' ? messages[key] : key;
  return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
// Server diagnostics may contain provider-specific text; keep unknown details intact.
export function diagnostic(text: string): string {
  const failed = text.match(/^Request failed \((\d+)\)$/);
  if (failed) return t('Request failed ({status})', { status: failed[1] });
  const validation = 'Teacher output failed format validation; no mastery recorded: ';
  if (text.startsWith(validation) && locale.language === 'zh-CN') return '教师输出未通过格式校验，未记录掌握：' + text.slice(validation.length);
  return Object.hasOwn(messages, text) ? t(text as MessageKey) : text;
}
